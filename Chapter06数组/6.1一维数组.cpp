//6.1.4 一维数组作为函数参数
    //数组名作为实参传递给形参时，传递的是数组首地址
    //函数定义格式
        //返回类型 函数名(元素类型 数组名[], int 元素个数)
        //e.g.
            void printArray(int arr[], int n){
                for (int i=0; i<n; i++)
                    cout << arr[i] << ' ';
            }
